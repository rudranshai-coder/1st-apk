/**
 * Room Entity tracking academic study sessions and hours spent on subjects like DPA, OS, Mathematics
 */
@Entity(tableName = "study_sessions")
data class StudySessionEntity(
    @PrimaryKey val id: String = UUID.randomUUID().toString(),
    val subject: String, // e.g. "DPA", "Operating Systems", "Discrete Mathematics"
    val topic: String, // e.g. "Normalization & SQL", "Banker's Algorithm", "Propositional Logic"
    val durationMinutes: Int, // e.g. 45, 60, 90, 120
    val timestamp: Long = System.currentTimeMillis(),
    val notes: String = "",
    val focusRating: Int = 5, // 1 to 5 stars
    val isCompleted: Boolean = true
) {
    val durationHoursFormatted: String
        get() {
            val hours = durationMinutes / 60
            val mins = durationMinutes % 60
            return when {
                hours > 0 && mins > 0 -> "${hours}h ${mins}m"
                hours > 0 -> "${hours}h"
                else -> "${mins}m"
            }
        }
}

data class SubjectStudyStat(
    val subject: String,
    val totalMinutes: Int,
    val sessionCount: Int
) {
    val totalHours: Double
        get() = totalMinutes / 60.0

    val totalHoursFormatted: String
        get() {
            val hours = totalMinutes / 60
            val mins = totalMinutes % 60
            return when {
                hours > 0 && mins > 0 -> "${hours}h ${mins}m"
                hours > 0 -> "${hours}h"
                else -> "${mins}m"
            }
        }
}

