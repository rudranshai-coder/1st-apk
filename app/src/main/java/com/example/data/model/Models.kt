data class UserSession(
    val userId: String = "student_bca_1",
    val name: String = "Rudransh Goyal",
    val email: String = "rudranshgoyal44@gmail.com",
    val semester: Int = 3,
    val university: String = "BCA Program",
    val specialization: String = "BCA + AI & Data Science",
    val studyStreakDays: Int = 14,
    val questionsSolved: Int = 142,
    val isGuest: Boolean = false
) {
    val shortName: String
        get() {
            val trimmed = name.trim()
            if (trimmed.isEmpty()) return "Student"
            val first = trimmed.split("\\s+".toRegex()).firstOrNull() ?: trimmed
            return if (first.length > 11) first.take(11) + "…" else first
        }

    val greetingText: String
        get() {
            val hour = java.util.Calendar.getInstance().get(java.util.Calendar.HOUR_OF_DAY)
            val timeGreeting = when (hour) {
                in 5..11 -> "Good morning"
                in 12..16 -> "Good afternoon"
                else -> "Good evening"
            }
            return "$timeGreeting, $shortName 👋"
        }
}

